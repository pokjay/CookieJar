-- Company equity grants (equity appreciation rights) for the Equity page.
--
-- Deliberately standalone: nothing in the net-worth / overview queries reads
-- this table, so grants are shown and played with on their own page without
-- being added to the household's total net worth.
CREATE TABLE moneyman.equity_grants (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text        NOT NULL DEFAULT '',
    -- Grant / vesting-start date. Vesting runs monthly from here after the cliff.
    grant_date    date,
    shares        numeric     NOT NULL DEFAULT 0,
    -- Exercise price per share, in USD.
    strike        numeric     NOT NULL DEFAULT 0,
    vesting_years numeric     NOT NULL DEFAULT 4,
    cliff_months  integer     NOT NULL DEFAULT 12,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

-- migrate:down
DROP TABLE IF EXISTS moneyman.equity_grants;
